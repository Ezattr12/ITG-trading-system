/**
 * Coach — three segments over the trader's real data:
 *
 * - "Ask the coach" (Phase 26): the Interactive AI Coach.
 *   Questions go to POST /api/mobile/coach/chat — the Bearer
 *   surface of the web chat, one shared engine. The app
 *   sends { message, history } and renders the server's
 *   structured answer (FACTS / INFERENCES / RECOMMENDATIONS,
 *   evidence line, narration-mode badge). There is NO coach
 *   or intent logic in the app and nothing is computed here.
 * - "Insights": the STORED weekly insights (ai_insights,
 *   generated by the deterministic Coach Engine and kept
 *   current by the Phase 20 trade-close pipeline).
 * - "Review": the weekly review (POST
 *   /api/mobile/reviews/weekly) and the backtesting log
 *   (POST /api/mobile/backtesting), added in Phase 25. XP
 *   figures shown are the endpoints' responses — awarded by
 *   the server cores, never computed here.
 */

type Segment = "chat" | "insights" | "review";

type ChatTurn =
  | { kind: "user"; content: string }
  | { kind: "coach"; answer: CoachChatAnswer };

/**
 * Suggested questions — every one is phrased to land on a
 * real intent in the engine's catalog (lib/coach/chat.ts
 * INTENT_RULES): weakness, last 30 trades, best strategy,
 * best session, repeated mistakes, psychology, discipline
 * trend, drawdown, risk behaviour, trading conditions,
 * monthly review, month comparison, improvement plan,
 * weekly focus.
 */
const SUGGESTIONS = [
  "What is my biggest trading weakness?",
  "Analyze my last 30 trades",
  "Which strategy performs best?",
  "Which session performs best?",
  "What mistakes do I keep making?",
  "How is my psychology affecting my results?",
  "How is my discipline trending?",
  "What is my drawdown?",
  "Am I risking too much per trade?",
  "When do I trade best?",
  "Give me a monthly review",
  "Compare this month with last month",
  "How can I improve my trading?",
  "What should I focus on this week?",
];

/** The web chat's evidence line, in the app's display formatting. */
function evidenceLine(e: CoachChatEvidence): string {
  const parts: string[] = [e.scope];
  if (e.tradesCount !== null) parts.push(`${e.tradesCount} closed trades`);
  if (e.totalPnl !== null) parts.push(`total P&L ${formatMoney(e.totalPnl)}`);
  if (e.winRate !== null) parts.push(`win rate ${formatPct(e.winRate)}`);
  if (e.profitFactor !== null)
    parts.push(`profit factor ${formatNumber(e.profitFactor)}`);
  if (e.avgR !== null) parts.push(`average R ${formatNumber(e.avgR)}`);
  return parts.join(" · ");
}

/**
 * One coach answer, rendered EXACTLY as the server
 * structured it: the honest narration-mode badge
 * ("Deterministic analysis" vs "AI-narrated · <provider>"),
 * a "Not enough data yet" badge for insufficient_data
 * answers (rendered as an answer, never as an error), then
 * the three labelled sections and the evidence line.
 */
function CoachAnswerCard({ answer }: { answer: CoachChatAnswer }) {
  const section = (title: string, accent: string, lines: string[]) =>
    lines.length === 0 ? null : (
      <View key={title} style={{ gap: 4 }}>
        <Text style={[shared.label, { color: accent }]}>{title}</Text>
        {lines.map((line, i) => (
          <View key={i} style={styles.bulletRow}>
            <Text style={[styles.bullet, { color: accent }]}>•</Text>
            <Text style={[shared.body, { flex: 1 }]}>{line}</Text>
          </View>
        ))}
      </View>
    );
  return (
    <GlassCard>
      <View style={styles.badgeRow}>
        <View
          style={[
            styles.badge,
            answer.narration === "llm" ? styles.badgeLlm : styles.badgeMuted,
          ]}
        >
          <Text
            style={[
              styles.badgeText,
              {
                color:
                  answer.narration === "llm"
                    ? tokens.auroraViolet
                    : tokens.textMuted,
              },
            ]}
          >
            {answer.narration === "llm"
              ? `AI-narrated${answer.narrationProvider ? ` · ${answer.narrationProvider}` : ""}`
              : "Deterministic analysis"}
          </Text>
        </View>
        {answer.status === "insufficient_data" ? (
          <View style={[styles.badge, styles.badgeWarning]}>
            <Text style={[styles.badgeText, { color: tokens.warning }]}>
              Not enough data yet
            </Text>
          </View>
        ) : null}
      </View>
      {section("Facts", tokens.auroraCyan, answer.facts)}
      {section("Inferences", tokens.auroraViolet, answer.inferences)}
      {section("Recommendations", tokens.profit, answer.recommendations)}
      <Text style={shared.muted}>Evidence: {evidenceLine(answer.evidence)}.</Text>
    </GlassCard>
  );
}

function SegmentedControl({
  value,
  onChange,
}: {
  value: Segment;
  onChange: (segment: Segment) => void;
}) {
  const options: { value: Segment; label: string }[] = [
    { value: "chat", label: "Ask the coach" },
    { value: "insights", label: "Insights" },
    { value: "review", label: "Review" },
  ];
  return (
    <View style={styles.segmentRow}>
      {options.map((option) => {
        const selected = option.value === value;
        return (
          <Pressable
            key={option.value}
            accessibilityRole="button"
            onPress={() => onChange(option.value)}
            style={[styles.segment, selected && styles.segmentSelected]}
          >
            <Text style={[styles.segmentText, selected && styles.segmentTextSelected]}>
              {option.label}
            </Text>
          </Pressable>
        );
      })}
    </View>
  );
}

export default function CoachScreen() {
  const { session } = useAuth();
  const [segment, setSegment] = useState<Segment>("chat");
  const [insights, setInsights] = useState<AiInsightRow[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  const load = useCallback(async () => {
    if (!session) return;
    setLoading(true);
    setError(null);
    const { data, error: queryError } = await supabase
      .from("ai_insights")
      .select("*")
      .eq("user_id", session.user.id)
      .order("generated_at", { ascending: false })
      .limit(20);
    if (queryError) {
      setError(queryError.message);
    } else {
      setInsights((data ?? []) as AiInsightRow[]);
    }
    setLoading(false);
  }, [session]);

  useEffect(() => {
    void load();
  }, [load]);

  /* -------- Interactive coach chat (POST /api/mobile/coach/chat) -------- */
  const [turns, setTurns] = useState<ChatTurn[]>([]);
  const [input, setInput] = useState("");
  const [pending, setPending] = useState(false);
  const [chatError, setChatError] = useState<string | null>(null);
  const chatScrollRef = useRef<ElementRef<typeof ScrollView>>(null);

  async function ask(question: string) {
    const message = question.trim();
    if (message === "" || pending) return; // single-flight: no double-send
    setChatError(null);
    setPending(true);
    // The contract's history: the last 6 turns, with coach
    // turns carried as their section text (the web chat's
    // exact construction). The server bounds it again and
    // never lets it widen the data scope.
    const history: CoachChatHistoryTurn[] = turns.slice(-6).map((turn) =>
      turn.kind === "user"
        ? { role: "user" as const, content: turn.content }
        : {
            role: "assistant" as const,
            content: [
              ...turn.answer.facts,
              ...turn.answer.inferences,
              ...turn.answer.recommendations,
            ].join("\n"),
          },
    );
    setTurns((prev) => [...prev, { kind: "user", content: message }]);
    setInput("");
    try {
      const answer = await askCoach(message, history);
      setTurns((prev) => [...prev, { kind: "coach", answer }]);
    } catch (e) {
      setChatError(
        e instanceof Error
          ? e.message
          : "The coach could not answer just now. Please try again.",
      );
    } finally {
      setPending(false);
    }
  }

  function resetChat() {
    if (pending) return;
    setTurns([]);
    setInput("");
    setChatError(null);
  }

  /* -------- Weekly review form (POST /api/mobile/reviews/weekly) -------- */
  const [weekDate, setWeekDate] = useState(toDateText(new Date()));
  const weekStart = mondayOfWeek(weekDate);
  const [reviewText, setReviewText] = useState("");
  const [mainMistake, setMainMistake] = useState("");
  const [focusNextWeek, setFocusNextWeek] = useState("");
  const [reviewSubmitting, setReviewSubmitting] = useState(false);
  const [reviewError, setReviewError] = useState<string | null>(null);
  const [reviewSuccess, setReviewSuccess] = useState<string | null>(null);

  // Pre-fill from the stored review for the selected week
  // (the core upserts by user + week_start_date).
  useEffect(() => {
    if (!session || !isDateText(weekDate)) return;
    let cancelled = false;
    supabase
      .from("weekly_reviews")
      .select("*")
      .eq("user_id", session.user.id)
      .eq("week_start_date", weekStart)
      .maybeSingle()
      .then(({ data }) => {
        if (cancelled) return;
        const row = (data as WeeklyReviewRow | null) ?? null;
        setReviewText(row?.review_text ?? "");
        setMainMistake(row?.main_mistake ?? "");
        setFocusNextWeek(row?.focus_next_week ?? "");
      });
    return () => {
      cancelled = true;
    };
  }, [session, weekDate, weekStart]);

  async function handleWeeklyReview() {
    if (reviewSubmitting) return;
    if (!isDateText(weekDate)) return setReviewError("Enter a valid date (YYYY-MM-DD).");
    if (reviewText.trim() === "")
      return setReviewError("Write at least a short reflection (10 characters).");
    setReviewError(null);
    setReviewSuccess(null);
    setReviewSubmitting(true);
    try {
      const result = await saveWeeklyReview({
        weekStartDate: weekDate,
        reviewText: reviewText.trim(),
        mainMistake: textOrNull(mainMistake),
        focusNextWeek: textOrNull(focusNextWeek),
      });
      setReviewSuccess(
        result.xp_awarded > 0
          ? `Weekly review saved — the server awarded +${result.xp_awarded} XP.`
          : "Weekly review saved — XP for this week was already awarded, so no new XP.",
      );
    } catch (e) {
      setReviewError(e instanceof Error ? e.message : "Something went wrong. Please try again.");
    } finally {
      setReviewSubmitting(false);
    }
  }

  /* -------- Backtesting log (POST /api/mobile/backtesting) -------- */
  const [btDate, setBtDate] = useState(toDateText(new Date()));
  const [btSessions, setBtSessions] = useState("");
  const [btSubmitting, setBtSubmitting] = useState(false);
  const [btError, setBtError] = useState<string | null>(null);
  const [btSuccess, setBtSuccess] = useState<string | null>(null);

  // Pre-fill with the day's stored TOTAL sessions.
  useEffect(() => {
    if (!session || !isDateText(btDate)) return;
    let cancelled = false;
    supabase
      .from("daily_activity")
      .select("activity_date, backtesting_sessions")
      .eq("user_id", session.user.id)
      .eq("activity_date", btDate)
      .maybeSingle()
      .then(({ data }) => {
        if (cancelled) return;
        const row = data as { backtesting_sessions: number | null } | null;
        setBtSessions(row?.backtesting_sessions ? String(row.backtesting_sessions) : "");
      });
    return () => {
      cancelled = true;
    };
  }, [session, btDate]);

  async function handleBacktesting() {
    if (btSubmitting) return;
    if (!isDateText(btDate)) return setBtError("Enter a valid date (YYYY-MM-DD).");
    const sessions = Number(btSessions);
    if (btSessions.trim() === "" || !Number.isInteger(sessions))
      return setBtError("Enter the total sessions for the day (a whole number).");
    setBtError(null);
    setBtSuccess(null);
    setBtSubmitting(true);
    try {
      const result = await logBacktesting(btDate, sessions);
      setBtSuccess(
        `Saved — ${result.sessions} session${result.sessions === 1 ? "" : "s"} logged for the day, ` +
          `${result.sessions_awarded} newly awarded, +${result.xp_awarded} XP.`,
      );
    } catch (e) {
      setBtError(e instanceof Error ? e.message : "Something went wrong. Please try again.");
    } finally {
      setBtSubmitting(false);
    }
  }

  const header = (
    <>
      <View style={shared.rowBetween}>
        <Text style={shared.title}>Coach</Text>
        {segment === "chat" && turns.length > 0 ? (
          <Pressable
            accessibilityRole="button"
            onPress={resetChat}
            disabled={pending}
            style={({ pressed }) => [styles.newChat, pressed && { opacity: 0.75 }]}
          >
            <Text style={styles.newChatText}>New chat</Text>
          </Pressable>
        ) : null}
      </View>
      <SegmentedControl value={segment} onChange={setSegment} />
    </>
  );

  if (segment === "chat") {
    return (
      <Screen scroll={false} contentStyle={{ flex: 1 }}>
        {header}
        <KeyboardAvoidingView
          style={{ flex: 1 }}
          behavior={Platform.OS === "ios" ? "padding" : "height"}
          keyboardVerticalOffset={Platform.OS === "ios" ? 56 : 0}
        >
          <ScrollView
            ref={chatScrollRef}
            style={{ flex: 1 }}
            contentContainerStyle={{ gap: 12, paddingBottom: 4 }}
            onContentSizeChange={() =>
              chatScrollRef.current?.scrollToEnd({ animated: true })
            }
            keyboardShouldPersistTaps="handled"
          >
            {turns.length === 0 ? (
              <GlassCard>
                <Text style={shared.body}>
                  Ask about your weakness, your strategies, a session, your
                  psychology, your discipline, your drawdown or your risk — or
                  tap a question below to start. Answers come only from your
                  own recorded trades; the coach cannot place or change
                  trades.
                </Text>
              </GlassCard>
            ) : null}
            {turns.map((turn, i) =>
              turn.kind === "user" ? (
                <View key={i} style={styles.userRow}>
                  <View style={styles.userBubble}>
                    <Text style={shared.body}>{turn.content}</Text>
                  </View>
                </View>
              ) : (
                <CoachAnswerCard key={i} answer={turn.answer} />
              ),
            )}
            {pending ? (
              <View style={styles.pendingRow}>
                <ActivityIndicator color={tokens.auroraViolet} size="small" />
                <Text style={shared.muted}>Analysing your trades…</Text>
              </View>
            ) : null}
          </ScrollView>

          <ScrollView
            horizontal
            showsHorizontalScrollIndicator={false}
            contentContainerStyle={styles.chipScroll}
            keyboardShouldPersistTaps="handled"
            style={{ flexGrow: 0 }}
          >
            {SUGGESTIONS.map((suggestion) => (
              <Pressable
                key={suggestion}
                accessibilityRole="button"
                disabled={pending}
                onPress={() => void ask(suggestion)}
                style={[styles.chip, pending && { opacity: 0.45 }]}
              >
                <Text style={styles.chipText}>{suggestion}</Text>
              </Pressable>
            ))}
          </ScrollView>

          <FormError message={chatError} />
          <View style={styles.composer}>
            <TextInput
              value={input}
              onChangeText={setInput}
              placeholder="Ask about your trading…"
              placeholderTextColor={tokens.textMuted}
              multiline
              maxLength={1000}
              editable={!pending}
              style={styles.composerInput}
            />
            <Pressable
              accessibilityRole="button"
              disabled={pending || input.trim() === ""}
              onPress={() => void ask(input)}
              style={({ pressed }) => [
                styles.sendButton,
                (pending || input.trim() === "" || pressed) && { opacity: 0.55 },
              ]}
            >
              <Text style={styles.sendButtonText}>Ask</Text>
            </Pressable>
          </View>
        </KeyboardAvoidingView>
      </Screen>
    );
  }

  return (
    <Screen>
      {header}
      {segment === "insights" ? (
        loading ? (
          <LoadingState label="Loading your insights…" />
        ) : (
          <>
            <GlassCard>
              <Text style={{ color: tokens.auroraViolet, fontWeight: "700", fontSize: 14 }}>
                Your stored weekly insights
              </Text>
              <Text style={shared.muted}>
                Generated from your real trades by the TraderOS Coach Engine and
                kept current as you journal. For a conversation with the coach,
                switch to Ask the coach.
              </Text>
            </GlassCard>
            {error ? <ErrorState message={error} /> : null}
            {!error && insights.length === 0 ? (
              <EmptyState
                title="No insights yet"
                body="Weekly insights are generated from your closed trades. Once a week has enough trades, its insights will appear here."
              />
            ) : null}
            {insights.map((insight) => (
              <GlassCard key={insight.id}>
                <Text style={shared.label}>{titleCase(insight.insight_type)}</Text>
                <Text style={shared.body}>{insight.summary}</Text>
                <Text style={shared.muted}>
                  {insight.period_start && insight.period_end
                    ? `${formatDate(insight.period_start)} → ${formatDate(insight.period_end)}`
                    : `Generated ${formatDate(insight.generated_at)}`}
                </Text>
              </GlassCard>
            ))}
          </>
        )
      ) : (
        <>
          <GlassCard>
            <Text style={shared.heading}>Weekly review</Text>
            <View style={{ gap: 14 }}>
              <View style={shared.rowBetween}>
                <GhostButton
                  label="← Prev week"
                  onPress={() => setWeekDate(shiftDate(weekStart, -7))}
                />
                <Text style={shared.muted}>Week of {formatDate(weekStart)}</Text>
                <GhostButton
                  label="Next week →"
                  onPress={() => setWeekDate(shiftDate(weekStart, 7))}
                />
              </View>
              <TextField
                label="Week starting (any day in the week)"
                value={weekDate}
                onChangeText={setWeekDate}
                placeholder="YYYY-MM-DD"
                keyboardType="number-pad"
                autoCapitalize="none"
                hint="The server snaps the date to that week's Monday, like web."
              />
              <TextField
                label="Review"
                value={reviewText}
                onChangeText={setReviewText}
                placeholder="How did the week go? What did you learn?"
                multiline
                maxLength={5000}
              />
              <TextField
                label="Main mistake (optional)"
                value={mainMistake}
                onChangeText={setMainMistake}
                maxLength={500}
              />
              <TextField
                label="Focus next week (optional)"
                value={focusNextWeek}
                onChangeText={setFocusNextWeek}
                maxLength={500}
              />
              <FormSuccess message={reviewSuccess} />
              <SubmitBar
                label="Save weekly review"
                onPress={handleWeeklyReview}
                submitting={reviewSubmitting}
                error={reviewError}
              />
            </View>
          </GlassCard>

          <GlassCard>
            <Text style={shared.heading}>Log backtesting</Text>
            <View style={{ gap: 14 }}>
              <TextField
                label="Date"
                value={btDate}
                onChangeText={setBtDate}
                placeholder="YYYY-MM-DD"
                keyboardType="number-pad"
                autoCapitalize="none"
              />
              <TextField
                label="Total sessions that day"
                value={btSessions}
                onChangeText={setBtSessions}
                placeholder="0"
                keyboardType="number-pad"
                hint="The day's TOTAL (1–10), not an increment — re-saving the same total awards nothing twice; raising it awards only the new sessions at +15 XP each."
              />
              <FormSuccess message={btSuccess} />
              <SubmitBar
                label="Save backtesting"
                onPress={handleBacktesting}
                submitting={btSubmitting}
                error={btError}
              />
            </View>
          </GlassCard>
        </>
      )}
    </Screen>
  );
}

