#!/usr/bin/env node
/**
 * Vendor @itg/calc into apps/mobile/vendor/itg-calc.
 *
 * The mobile app is intentionally standalone (it installs
 * outside the npm workspaces — see the APK workflow), so it
 * cannot resolve the workspace's @itg/calc package directly.
 * This script copies the canonical package source next to the
 * app and writes a minimal dependency-free package.json for
 * it, so `npm install` in apps/mobile links it as
 * "@itg/calc": "file:./vendor/itg-calc".
 *
 * Why vendor at all: profile completion has ONE canonical
 * implementation (packages/calc/src/profile-completion.ts)
 * shared by web and mobile. The profile screen deep-imports
 * "@itg/calc/src/profile-completion" — a dependency-free
 * module — so Metro never pulls in the decimal.js-based
 * modules that share the package. The whole src tree is
 * copied for fidelity with the canonical package (mirroring
 * how the web deploy vendors @itg/calc into apps/web).
 *
 * The vendored copy is a build artifact: it is gitignored
 * (apps/mobile/.gitignore) and regenerated by this script —
 * locally before `npm install`, and in CI before the mobile
 * install step (.github/workflows/mobile-apk.yml). Never edit
 * the copy by hand; edit packages/calc and re-run this.
 */
import {
  cpSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const mobileDir = dirname(dirname(fileURLToPath(import.meta.url)));
const repoRoot = dirname(dirname(mobileDir));
const calcDir = join(repoRoot, "packages", "calc");
const vendorDir = join(mobileDir, "vendor", "itg-calc");

const realPkg = JSON.parse(
  readFileSync(join(calcDir, "package.json"), "utf8"),
);

rmSync(vendorDir, { recursive: true, force: true });
mkdirSync(vendorDir, { recursive: true });
cpSync(join(calcDir, "src"), join(vendorDir, "src"), { recursive: true });

// Minimal manifest: NO dependencies. The package's real
// dependency (decimal.js) is only used by the trade-math
// modules, which the app never imports — the completion module
// it does import is dependency-free.
writeFileSync(
  join(vendorDir, "package.json"),
  `${JSON.stringify(
    {
      name: "@itg/calc",
      version: realPkg.version,
      private: true,
      main: "src/index.ts",
      types: "src/index.ts",
    },
    null,
    2,
  )}\n`,
);

console.log(`Vendored @itg/calc@${realPkg.version} -> ${vendorDir}`);
