import PDFDocument from "pdfkit";
import type { CriterionResult } from "./types";

/**
 * Certificate PDF (Phase 8, spec §26).
 *
 * Generated on demand from the stored certificate row — the PDF
 * is never stored in Supabase Storage in this phase (that is the
 * Phase 13 step), and the route handler says so. Every value on
 * the PDF comes from the certificate record and its
 * `criteria_met` evidence; nothing is invented for the document.
 *
 * Library choice: pdfkit (0.17.x). It is a plain Node PDF
 * writer with no browser/React dependency, it works in a Next.js
 * Route Handler, and it keeps the certificate layout in one
 * small function instead of a component tree. @react-pdf/renderer
 * would have added a React render pipeline for a single static
 * document, so pdfkit is the smaller, more maintainable choice.
 */

export interface CertificatePdfData {
  traderName: string;
  certificateId: string;
  monthLabel: string;
  criteria: CriterionResult[];
  issuedAt: string | null;
}

/** Build the certificate PDF and return it as a Buffer. */
export function buildCertificatePdf(data: CertificatePdfData): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", margin: 72 });
    const chunks: Buffer[] = [];
    doc.on("data", (chunk: Buffer) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    const pageWidth = doc.page.width - 144;

    // Border frame.
    doc
      .rect(36, 36, doc.page.width - 72, doc.page.height - 72)
      .lineWidth(2)
      .strokeColor("#1e293b")
      .stroke();
    doc
      .rect(44, 44, doc.page.width - 88, doc.page.height - 88)
      .lineWidth(0.5)
      .strokeColor("#64748b")
      .stroke();

    doc.moveDown(3);
    doc
      .fontSize(13)
      .fillColor("#475569")
      .text("ITG — INSTITUTIONAL TRADING GROUP", { align: "center" });
    doc.moveDown(0.5);
    doc
      .fontSize(28)
      .fillColor("#0f172a")
      .text("Performance Certificate", { align: "center" });
    doc.moveDown(0.5);
    doc
      .fontSize(12)
      .fillColor("#475569")
      .text("Awarded for consistent journaling, risk discipline, trading routine and performance review.", {
        align: "center",
        width: pageWidth,
      });

    doc.moveDown(2);
    doc.fontSize(11).fillColor("#475569").text("This certificate is awarded to", { align: "center" });
    doc.moveDown(0.5);
    doc.fontSize(24).fillColor("#0f172a").text(data.traderName, { align: "center" });
    doc.moveDown(1);
    doc
      .fontSize(13)
      .fillColor("#0f172a")
      .text(`For the month of ${data.monthLabel}`, { align: "center" });

    doc.moveDown(2);
    doc.fontSize(12).fillColor("#0f172a").text("Criteria met", { align: "left" });
    doc.moveDown(0.5);
    for (const c of data.criteria) {
      doc
        .fontSize(11)
        .fillColor("#166534")
        .text(`✓  ${c.label} — ${c.detail}`, { width: pageWidth });
      doc.moveDown(0.25);
    }

    doc.moveDown(2);
    doc
      .fontSize(11)
      .fillColor("#475569")
      .text(`Certificate ID: ${data.certificateId}`, { align: "center" });
    if (data.issuedAt) {
      doc.text(
        `Issued: ${new Date(data.issuedAt).toISOString().slice(0, 10)}`,
        { align: "center" },
      );
    }
    doc.moveDown(1);
    doc
      .fontSize(9)
      .fillColor("#94a3b8")
      .text(
        "Generated by ITG TraderOS from the trader's stored trading record. " +
          "This certificate records that the month's requirements were met; it is not a guarantee of future performance.",
        { align: "center", width: pageWidth },
      );

    doc.end();
  });
}
