import PDFDocument from "pdfkit";
import type { ReportSummary } from "./types";
import { REPORT_TYPE_LABELS } from "./types";
import { CATALOG_REPORT_LABELS, type CatalogReport } from "./catalog";

/**
 * Report PDF (Phase 8, spec §27). Same library choice as the
 * certificate PDF (pdfkit — see lib/certificates/pdf.ts): a plain
 * Node PDF writer, no React pipeline, generated on demand from
 * the computed summary. The PDF is a download, not a file stored
 * in Supabase Storage in this phase.
 */

function fmt(n: number | null, digits = 2): string {
  if (n === null || n === undefined) return "—";
  return n.toFixed(digits);
}

function money(n: number): string {
  return `${n >= 0 ? "+" : ""}${n.toFixed(2)}`;
}

/** Build a report PDF from a computed summary and return it as a Buffer. */
export function buildReportPdf(
  summary: ReportSummary,
  traderName: string,
): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", margin: 56 });
    const chunks: Buffer[] = [];
    doc.on("data", (chunk: Buffer) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    const width = doc.page.width - 112;
    const section = (title: string) => {
      doc.moveDown(1);
      doc.fontSize(13).fillColor("#0f172a").text(title);
      doc.moveDown(0.4);
    };
    const line = (label: string, value: string) => {
      doc.fontSize(11).fillColor("#334155").text(`${label}: ${value}`);
    };

    doc.fontSize(18).fillColor("#0f172a").text("ITG TraderOS — Trading Report");
    doc
      .fontSize(11)
      .fillColor("#475569")
      .text(
        `${REPORT_TYPE_LABELS[summary.type]} report · ${summary.periodStart} to ${summary.periodEnd} · ${traderName}`,
      );

    section("Performance");
    line("Trades", String(summary.tradesCount));
    line("Wins / Losses / Breakeven", `${summary.wins} / ${summary.losses} / ${summary.breakeven}`);
    line("Total P&L", money(summary.totalPnl));
    line("Win rate", summary.winRate === null ? "—" : `${fmt(summary.winRate, 1)}%`);
    line("Average win", fmt(summary.avgWin));
    line("Average loss", fmt(summary.avgLoss));
    line("Profit factor", fmt(summary.profitFactor));
    line("Expectancy (per trade)", fmt(summary.expectancy));
    line("Average R", fmt(summary.avgR));

    section("Discipline & goals");
    line(
      "Journal completion",
      summary.journalCompletionPct === null ? "—" : `${summary.journalCompletionPct}%`,
    );
    line(
      "Trades with a stop-loss",
      summary.disciplinePct === null ? "—" : `${summary.disciplinePct}%`,
    );
    line("Goals completed", `${summary.goalsCompleted} of ${summary.goalsTotal}`);

    if (summary.byStrategy.length > 0) {
      section("By strategy");
      for (const row of summary.byStrategy) {
        line(
          row.name,
          `${row.trades} trades · ${row.wins} wins · ${money(row.totalPnl)}`,
        );
      }
    }

    if (summary.mostFrequentLosingSetup) {
      section("Most frequent losing setup");
      doc
        .fontSize(11)
        .fillColor("#334155")
        .text(
          `${summary.mostFrequentLosingSetup.name} — ${summary.mostFrequentLosingSetup.losses} losing trades.`,
          { width },
        );
    }

    section("Recommendations");
    for (const rec of summary.recommendations) {
      doc.fontSize(11).fillColor("#334155").text(`•  ${rec}`, { width });
      doc.moveDown(0.3);
    }

    doc.moveDown(1);
    doc
      .fontSize(9)
      .fillColor("#94a3b8")
      .text(
        "Generated by ITG TraderOS from the trader's stored trading record. Recommendations are rule-based observations from this period's own data.",
        { width },
      );

    doc.end();
  });
}

/**
 * Catalog report PDF (Phase 24). Renders the SAME composed
 * report object the Reports page renders (`lib/reports/catalog.ts`)
 * — this builder computes nothing: every figure printed is
 * read off the object, and a section whose analysis is
 * `insufficient_data` (or a period with no trades) prints its
 * honest note instead of numbers.
 */
export function buildCatalogReportPdf(
  report: CatalogReport,
  traderName: string,
): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", margin: 56 });
    const chunks: Buffer[] = [];
    doc.on("data", (chunk: Buffer) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    const width = doc.page.width - 112;
    const section = (title: string) => {
      doc.moveDown(1);
      doc.fontSize(13).fillColor("#0f172a").text(title);
      doc.moveDown(0.4);
    };
    const line = (label: string, value: string) => {
      doc.fontSize(11).fillColor("#334155").text(`${label}: ${value}`);
    };
    const note = (text: string) => {
      doc.fontSize(11).fillColor("#334155").text(text, { width });
    };
    const s = report.summary;

    doc
      .fontSize(18)
      .fillColor("#0f172a")
      .text(`ITG TraderOS — ${CATALOG_REPORT_LABELS[report.kind]} Report`);
    doc
      .fontSize(11)
      .fillColor("#475569")
      .text(
        `${report.period === "week" ? "Weekly" : "Monthly"} report · ${report.periodStart} to ${report.periodEnd} · ${traderName}`,
      );

    if (!report.hasData) {
      section("No data in this period");
      note(
        "No closed trades in this period — there is nothing to report yet. Journal your next trades and this report will fill in.",
      );
      doc.end();
      return;
    }

    section("Period summary");
    line("Trades", String(s.tradesCount));
    line("Wins / Losses / Breakeven", `${s.wins} / ${s.losses} / ${s.breakeven}`);
    line("Total P&L", money(s.totalPnl));
    line("Win rate", s.winRate === null ? "—" : `${fmt(s.winRate, 1)}%`);
    line("Profit factor", fmt(s.profitFactor));
    line("Expectancy (per trade)", fmt(s.expectancy));
    line("Average R", fmt(s.avgR));

    if (report.kind === "performance") {
      const dd = report.drawdown;
      section("Drawdown (this period)");
      if (dd.status !== "ok") {
        note(
          `Not enough closed trades in this period for a drawdown analysis (${dd.tradesCount} recorded; 5 are needed).`,
        );
      } else {
        line("Maximum drawdown", money(dd.maxDrawdown));
        line(
          "Maximum drawdown (% of peak profit)",
          dd.maxDrawdownPctOfPeak === null ? "—" : `${fmt(dd.maxDrawdownPctOfPeak, 1)}%`,
        );
        line("Current drawdown", money(dd.currentDrawdown));
        if (dd.episode) {
          line(
            "Worst episode",
            `${dd.episode.peakDate} to ${dd.episode.troughDate}${dd.episode.recovered ? ` (recovered ${dd.episode.recoveryDate ?? ""})` : " (not yet recovered)"}`,
          );
        }
      }
      if (s.byStrategy.length > 0) {
        section("By strategy");
        for (const row of s.byStrategy) {
          line(row.name, `${row.trades} trades · ${row.wins} wins · ${money(row.totalPnl)}`);
        }
      }
      if (s.bySession.length > 0) {
        section("By session");
        for (const row of s.bySession) {
          line(row.name, `${row.trades} trades · ${row.wins} wins · ${money(row.totalPnl)}`);
        }
      }
    }

    if (report.kind === "psychology") {
      const p = report.psychology;
      section("Psychology vs performance");
      if (p.status !== "ok") {
        note("No psychology records in this period — there is nothing to analyse yet.");
      } else {
        for (const row of p.byEmotion) {
          line(
            row.label,
            `${row.trades} trades · ${row.winRate === null ? "—" : `${fmt(row.winRate, 1)}% win rate`} · ${money(row.totalPnl)}`,
          );
        }
        for (const row of p.byConfidence) {
          line(
            row.label,
            `${row.trades} trades · ${row.winRate === null ? "—" : `${fmt(row.winRate, 1)}% win rate`} · ${money(row.totalPnl)}`,
          );
        }
        if (p.emotionStatement) note(p.emotionStatement);
        if (p.confidenceStatement) note(p.confidenceStatement);
      }
      const d = report.discipline;
      section("Discipline");
      line("Trades with a stop-loss", `${fmt(d.stopLossPct, 1)}%`);
      line("Journal completion", `${fmt(d.journalCompletionPct, 1)}%`);
      if (d.stopLoss.statement) note(d.stopLoss.statement);
      if (d.journaled.statement) note(d.journaled.statement);
      if (d.rating?.statement) note(d.rating.statement);
    }

    if (report.kind === "risk") {
      const r = report.risk;
      section("Risk behaviour (this period)");
      if (r.status !== "ok") {
        note("No closed trades in this period — there is nothing to analyse yet.");
      } else {
        if (r.distribution) {
          line(
            "Planned risk per trade",
            `avg ${money(r.distribution.avg)} · median ${money(r.distribution.median)} · min ${money(r.distribution.min)} · max ${money(r.distribution.max)} (${r.distribution.count} trades with a stop-loss)`,
          );
        }
        line("Trades without a stop-loss", String(r.withoutStopLossCount));
        line(
          "Per-trade risk limit",
          r.riskLimitPct === null
            ? "No limit configured"
            : `${fmt(r.riskLimitPct)}%${r.overLimitCount === null ? " (capital not on file — limit check unavailable)" : ` — ${r.overLimitCount} trade(s) over the limit`}`,
        );
        line(
          "Daily loss limit",
          r.dailyLossLimit === null
            ? "No limit configured"
            : `${money(r.dailyLossLimit)} — ${r.dailyLossBreachDays ?? 0} breach day(s)`,
        );
        if (r.worstDay) line("Worst day", `${r.worstDay.date}: ${money(r.worstDay.pnl)}`);
        line(
          "Leverage",
          r.maxLeverageUsed === null
            ? "—"
            : `max used ${r.maxLeverageUsed}x${r.leverageLimit === null ? "" : ` · limit ${r.leverageLimit}x · ${r.leverageOverCount ?? 0} over`}`,
        );
        line("Longest losing streak", String(r.maxConsecutiveLosses));
        line(
          "Stored risk events in period",
          `${r.riskEvents.total} (${r.riskEvents.critical} critical · ${r.riskEvents.warning} warning · ${r.riskEvents.positive} positive)`,
        );
      }
      section("Configured limits");
      line(
        "Risk rules",
        report.rules
          ? `max risk/trade ${report.rules.max_risk_per_trade_pct === null ? "not set" : `${report.rules.max_risk_per_trade_pct}%`} · max daily loss ${report.rules.max_daily_loss === null ? "not set" : money(report.rules.max_daily_loss)} · max leverage ${report.rules.max_leverage === null ? "not set" : `${report.rules.max_leverage}x`}`
          : "No active risk rules",
      );
      line(
        "Trading plan",
        report.plan
          ? `${report.plan.name} · risk/trade ${report.plan.risk_per_trade_pct === null ? "not set" : `${report.plan.risk_per_trade_pct}%`} · max daily loss ${report.plan.max_daily_loss === null ? "not set" : money(report.plan.max_daily_loss)}`
          : "No active trading plan",
      );
      if (report.periodRiskEvents.length > 0) {
        section("Risk events in this period");
        for (const e of report.periodRiskEvents) {
          line(e.created_at.slice(0, 10), `[${e.severity}] ${e.message}`);
        }
      }
      const dd = report.drawdown;
      section("Drawdown (this period)");
      if (dd.status !== "ok") {
        note(
          `Not enough closed trades in this period for a drawdown analysis (${dd.tradesCount} recorded; 5 are needed).`,
        );
      } else {
        line("Maximum drawdown", money(dd.maxDrawdown));
        line("Current drawdown", money(dd.currentDrawdown));
      }
    }

    if (report.kind === "strategy") {
      if (s.byStrategy.length > 0) {
        section("By strategy");
        for (const row of s.byStrategy) {
          line(
            row.name,
            `${row.trades} trades · ${row.winRate === null ? "—" : `${fmt(row.winRate, 1)}% win rate`} · ${money(row.totalPnl)}`,
          );
        }
      }
      section("Most / least profitable strategy (3+ trades)");
      line(
        "Most profitable",
        report.bestStrategy
          ? `${report.bestStrategy.name} — ${money(report.bestStrategy.totalPnl)} across ${report.bestStrategy.trades} trades`
          : "No strategy has 3 or more trades in this period yet.",
      );
      line(
        "Least profitable",
        report.worstStrategy
          ? `${report.worstStrategy.name} — ${money(report.worstStrategy.totalPnl)} across ${report.worstStrategy.trades} trades`
          : "Only one strategy qualifies, or none do.",
      );
      if (report.strategySessionRows.length > 0) {
        section("Strategy by session (3+ trades)");
        for (const row of report.strategySessionRows) {
          line(row.label, `${row.trades} trades · ${money(row.totalPnl)}`);
        }
      }
      if (s.mostFrequentLosingSetup) {
        section("Most frequent losing setup");
        note(
          `${s.mostFrequentLosingSetup.name} — ${s.mostFrequentLosingSetup.losses} losing trades.`,
        );
      }
    }

    if (report.kind === "coach") {
      if (report.digest && report.digest.coachFindings.length > 0) {
        section("Coach findings for this period");
        for (const f of report.digest.coachFindings) {
          doc.fontSize(11).fillColor("#334155").text(`•  ${f.title}`, { width });
          if (f.recommendation) note(`   ${f.recommendation}`);
          doc.moveDown(0.3);
        }
      }
      if (report.storedInsights.length > 0) {
        section("Stored coach insights in this period");
        for (const row of report.storedInsights) {
          doc
            .fontSize(11)
            .fillColor("#334155")
            .text(`•  ${row.summary}`, { width });
          if (row.metrics_snapshot?.recommendation) {
            note(`   ${row.metrics_snapshot.recommendation}`);
          }
          doc.moveDown(0.3);
        }
      }
      if (
        (!report.digest || report.digest.coachFindings.length === 0) &&
        report.storedInsights.length === 0
      ) {
        section("Coach findings for this period");
        note(
          "No coach findings were generated for this period — the deterministic coach needs at least 3 closed trades in a week to analyse it.",
        );
      }
      if (report.digest && report.digest.focus.length > 0) {
        section("Focus for the next period");
        for (const a of report.digest.focus) {
          doc.fontSize(11).fillColor("#334155").text(`•  ${a.title} — ${a.evidence}`, { width });
          doc.moveDown(0.3);
        }
      }
      section("Recommendations");
      for (const rec of report.recommendations) {
        doc.fontSize(11).fillColor("#334155").text(`•  ${rec}`, { width });
        doc.moveDown(0.3);
      }
    }

    doc.moveDown(1);
    doc
      .fontSize(9)
      .fillColor("#94a3b8")
      .text(
        "Generated by ITG TraderOS from the trader's stored trading record. Every figure comes from the same report composition the in-app Reports page renders; nothing is estimated.",
        { width },
      );

    doc.end();
  });
}
